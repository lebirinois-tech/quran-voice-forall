import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

export function configureHifzAndroid(root = '.') {
  const config = JSON.parse(readFileSync(join(root, 'capacitor.config.json'), 'utf8'));
  const appId = config.appId;
  if (!/^[A-Za-z][A-Za-z0-9_]*(\.[A-Za-z][A-Za-z0-9_]*)+$/.test(appId)) throw new Error('Invalid Android appId');
  const manifestPath = join(root, 'android/app/src/main/AndroidManifest.xml');
  let manifest = readFileSync(manifestPath, 'utf8');
  const additions = [
    ['android.permission.RECORD_AUDIO', '<uses-permission android:name="android.permission.RECORD_AUDIO" />'],
    ['android.permission.MODIFY_AUDIO_SETTINGS', '<uses-permission android:name="android.permission.MODIFY_AUDIO_SETTINGS" />'],
    ['android.hardware.microphone', '<uses-feature android:name="android.hardware.microphone" android:required="false" />'],
    ['android.speech.RecognitionService', '<queries><intent><action android:name="android.speech.RecognitionService" /></intent></queries>'],
  ];
  for (const [marker, xml] of additions) {
    if (!manifest.includes(marker)) manifest = manifest.replace('</manifest>', `    ${xml}\n</manifest>`);
  }
  writeFileSync(manifestPath, manifest);
  const javaRoot = join(root, 'android/app/src/main/java', ...appId.split('.'));
  mkdirSync(javaRoot, { recursive: true });
  const source = readFileSync(join(dirname(fileURLToPath(import.meta.url)), 'HifzSpeechPlugin.java'), 'utf8');
  writeFileSync(join(javaRoot, 'HifzSpeechPlugin.java'), source.replace('package app.quranaccespourtous.mobile;', `package ${appId};`));
  const activityPath = join(javaRoot, 'MainActivity.java');
  let activity = readFileSync(activityPath, 'utf8');
  if (!activity.includes('registerPlugin(HifzSpeechPlugin.class)')) {
    // The Android platform is freshly generated by Capacitor in the APK workflow.
    if (!/extends BridgeActivity\s*\{\s*\}/.test(activity)) throw new Error('Unexpected MainActivity: register HifzSpeechPlugin manually');
    activity = activity.replace(/extends BridgeActivity\s*\{\s*\}/, `extends BridgeActivity {
    @Override
    public void onCreate(android.os.Bundle savedInstanceState) {
        registerPlugin(HifzSpeechPlugin.class);
        super.onCreate(savedInstanceState);
    }
}`);
    writeFileSync(activityPath, activity);
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) configureHifzAndroid();